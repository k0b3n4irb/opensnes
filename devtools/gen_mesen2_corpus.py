#!/usr/bin/env python3
"""Write testing/mesen2_corpus.toml: one screen per ROM of the console protocol, for a second-emulator comparison.

The list is not chosen here, it is read: the ROMs are the rows of docs/HARDWARE_VERIFICATION.md (the 26 rows, 25 distinct
ROMs: `input/controller` has two), the frame of the screen is the latest capture point of the ROM's luna manifest
(testing/manifest.toml), the same instant luna_runner.py compares against its visual baseline. The comparison itself
(luna against Mesen2, pixel by pixel, 5 bits per component, `row0 = 7` for the 7-line offset of Mesen2's core) is the
kit's `mesen2_screens --corpus`, run by luna's session under `lourd`; this file is the list it reads.

A ROM that needs a coprocessor firmware luna holds and Mesen2 may not (the DSP-1 row) stays in the file with a comment
saying so, because leaving it out is the silent way to lose a ROM. Rectangles admitted for a known difference are added
by hand under `[[entree.admit]]`, each with its reason; `--check` fails if the file is not what this script writes.

  python3 devtools/gen_mesen2_corpus.py            # (re)write
  python3 devtools/gen_mesen2_corpus.py --check    # exit 1 when the committed file is stale
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "testing"))
import hardware_preflight as hp  # noqa: E402
import luna_runner as lr  # noqa: E402

OUT = ROOT / "testing" / "mesen2_corpus.toml"
FIRMWARE_GATED = {"mode7/dsp1_ground": "needs dsp1b.rom, which luna loads from its firmware folder; Mesen2 needs it in its own"}
DEVICE = {"input/mouse": "reads a mouse luna does not model: boot screen only",
          "input/superscope": "reads a Super Scope luna does not model: boot screen only"}


def entry_name(key: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", key.lower()).strip("_").replace("testing_fixtures_retired_examples_", "retired_")


def render() -> str:
    manifest = lr.load_manifest()
    roms = {lr.example_key(r): r for r in lr.discover_example_roms()}
    seen: set[str] = set()
    out = [
        "# GENERATED by devtools/gen_mesen2_corpus.py from docs/HARDWARE_VERIFICATION.md and testing/manifest.toml: do not edit",
        "# the entries (--check refuses a hand edit). No difference is admitted yet: the first `[[entree.admit]]` (with its reason) is a change of this generator.",
        "# Read by the kit's `mesen2_screens --corpus` (luna's second-opinion job, under `lourd`, MESEN2_JOBS=2).",
        "# Paths are relative to the root of this repository; each .sym sits beside its ROM (make examples fixtures).",
        "",
        "row0 = 7         # the 7-line offset of Mesen2's core: without it every screen reads DIFFERENT (measured by luna)",
        "frame0 = 0",
        "limit = 20000",
        "",
    ]
    for _, key in hp.protocol_rows():
        if key in seen:
            continue
        seen.add(key)
        rom = hp.protocol_rom(key, roms)
        if rom is None:
            raise SystemExit(f"gen_mesen2_corpus: no ROM for {key}: build first (make && make fixtures)")
        frame = max(lr.capture_frames(key, manifest))
        name = entry_name(key)
        out.append("[[entree]]")
        out.append(f'name = "{name}"')
        out.append(f'rom = "{rom.relative_to(ROOT).as_posix()}"')
        if key in FIRMWARE_GATED:
            out.append(f"# NOTE: {FIRMWARE_GATED[key]}")
        if key in DEVICE:
            out.append(f"# NOTE: {DEVICE[key]}")
        out.append("[[entree.screen]]")
        out.append('name = "fin"')
        out.append("[entree.screen.rom]")
        out.append(f"frame = {frame}")
        out.append("")
    return "\n".join(out)


def main(argv):
    text = render()
    if "--check" in argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("gen_mesen2_corpus: testing/mesen2_corpus.toml is not what the generator writes: rerun it")
            return 1
        print(f"OK: testing/mesen2_corpus.toml matches ({text.count('[[entree]]')} ROMs)")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count('[[entree]]')} ROMs")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
