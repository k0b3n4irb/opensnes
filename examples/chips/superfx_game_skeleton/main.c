/**
 * @file main.c
 * @brief Super FX game skeleton — a game loop at 60 fps while the GSU renders
 * @ingroup examples
 *
 * The shape of a Super FX game: the CPU runs the game every frame (here, a
 * sight steered with the D-pad, and music), the GSU renders the 3D view on
 * its own clock (here, a hologram turning above a square of the city at
 * night: a data cube, a smaller cube inside it, the struts between them and
 * the projector's beams), and the NMI moves each finished frame to VRAM.
 * Nothing waits for anything else.
 *
 * - The renderer runs from the GSU's code cache (gsuCacheLoad /
 *   gsuStartCached): the ROM stays the CPU's, so the game loop runs during
 *   the job.
 * - Two framebuffers in Game Pak RAM, two char blocks in VRAM: gsuPresent()
 *   queues the frame the job just drew, the next job draws in the other
 *   buffer, and the NMI moves the queued one a piece per VBlank, taking
 *   Game Pak RAM from the GSU for each piece. BG1 switches to the new block
 *   only once all of it has landed.
 * - A 40 + 40 line letterbox (gsuSetupHdmaBlanking) lengthens the blank the
 *   NMI transfers in: a 16 KB frame lands in two VBlanks, 30 fps.
 *
 * @par SNES Concepts
 * - Super FX code cache: a job that leaves the ROM to the CPU
 * - Game Pak RAM time-sharing (SCMR RAN) between the GSU and the NMI's DMA
 * - Double buffering by BG1 char base (BG12NBA), swapped after a whole frame
 * - HDMA letterbox on INIDISP to extend the VBlank transfer window
 * - A GSU bitmap BG over a picture BG: the GSU clears to colour 0, which
 *   is transparent, so BG2's square shows wherever the hologram is not
 * - OBJ layer over both
 * - SNESMOD music fed every frame (snesmodProcess) during GSU work
 * - The CPU projects, the GSU draws: 19 points a job in Game Pak RAM, joined
 *   by the GSU through an edge table written once at boot
 * - Cartridge RAM from C through FAR pointers ($70:8000)
 *
 * @par What to Observe
 * - The hologram turns and bobs at 30 fps above the projector in the middle
 *   of the square; the sight follows the D-pad at 60 fps, whatever the GSU
 *   is doing, and the music never stutters.
 * - No torn or half-drawn hologram: a frame is shown only once complete.
 *
 * @par Modules Used
 * console, sprite, dma, background, asset, input, superfx, snesmod
 *
 * @see superfx.h (gsuPresent, gsuStartCached), docs/tutorials/superfx_advanced.md
 */

#include <snes.h>
#include <snes/superfx.h>
#include <snes/snesmod.h>
#include "soundbank.h"   /* generated by opensnes-music from SOUNDBANK_SRC */
#include "res/square.inc" /* generated: the square (BG2), DECLARE_BG_ASSET */
#include "res/sight.inc"  /* generated: sight_tiles[], sight_pal[], the pad's sight */

/* gsu_loader.asm */
extern const u8 gsu_cube[], gsu_cube_end[];   /**< the cache-resident renderer */

/** @brief Game Pak RAM past the two framebuffers, as the CPU sees it (bank
 * $70): the points' x, their y, the edge table. The renderer reads the same
 * three at $8000, $8020 and $8040 (gsu_cube.sfx). The CPU writes them only
 * while it owns the RAM: before the first job, or after gsuWait().
 * The pointers are FAR: a plain pointer reads and writes bank $00, and an
 * indexed store through ((u8 *)0x708040)[i] would land in ROM at $00:8040. */
#define POINT_X    ((u8 FAR *)0x708000)
/** @brief The points' y */
#define POINT_Y    ((u8 FAR *)0x708020)
/** @brief The edge table: 34 x (point, point, colour) */
#define EDGE_TABLE ((u8 FAR *)0x708040)

/** @brief Letterbox bands (lines): the NMI moves frames in VBlank + top band */
#define LETTERBOX_TOP    40
/** @brief Bottom band: at least one line keeps force blank across line 0 */
#define LETTERBOX_BOTTOM 40

/** @brief VRAM word addresses. BG1's two char blocks take $0000-$3FFF (16 KB
 * each), the square's 541 tiles $4000-$61CF. BG2's tiles run into the OBJ
 * name base ($6000), so the sight lives in the second name table: tile 256,
 * at $7000. The two 32x32 maps sit above it, clear of the sight's tiles. */
#define VRAM_BG1_A   0x0000
#define VRAM_BG1_B   0x2000
#define VRAM_BG2     0x4000
#define VRAM_OBJ     0x6000
#define VRAM_SIGHT   0x7000
#define VRAM_BG1_MAP 0x7800
#define VRAM_BG2_MAP 0x7C00

/** @brief The sight's first tile: the second name table (256 + 0) */
#define SIGHT_TILE   256

/** @brief Sight position (the game's state): its top-left corner */
u16 r_ship_x, r_ship_y;
/** @brief Game-loop frames (one per WaitForVBlank) */
u16 r_game_frames;
/** @brief GSU jobs started */
u16 r_jobs;
/** @brief The module's pattern position, sampled every frame */
u16 r_music_pos;

