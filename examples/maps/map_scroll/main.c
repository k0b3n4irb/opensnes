/**
 * @file main.c
 * @brief Scrolling map with animated sprite character
 * @ingroup examples
 *
 * A large Tiled map scrolls as Kit, the fox-kit courier, walks left and
 * right along a row of rooftops at night. The map engine streams only the
 * visible tiles to VRAM, so the map can be much wider than the screen. The
 * sprite cycles through 8 walk frames and flips horizontally based on
 * direction.
 *
 * This is the stepping stone between "static background" and
 * "continuous_scroll" — it teaches the map engine basics with a
 * simple player character.
 *
 * This began as the PVSnesLib "mapscroll" example by alekmaul; the map, its
 * tiles and Kit are ours (devtools/art_assets/build.py writes the Tiled map
 * and its tile sheet from assets/neo-lumen/).
 *
 * @par SNES Concepts
 * - Map engine: mapLoad / mapUpdate / mapUpdateCamera / mapVblank
 * - Camera-follow: sprite position drives the viewport
 * - Sprite animation: 8-frame walk cycle with horizontal flip
 * - oamSet for simple single-sprite rendering
 * - mapGetCameraX() / mapGetCameraY() for screen-relative sprite positioning
 *
 * @par What to Observe
 * - Press LEFT/RIGHT to move Kit along the roofs
 * - The background scrolls to follow the character
 * - Kit's walk advances one frame every 4 frames of movement
 * - Kit flips horizontally when changing direction
 *
 * @par Modules Used
 * console, sprite, dma, input, background, map
 *
 * @see map.h, sprite.h, input.h
 */

#include <snes.h>
#include <snes/map.h>

/*============================================================================
 * Assets (converted by the build from res/, one settings file beside each picture)
 *============================================================================*/

/** @brief The roofs' 802 tiles, Kit's 32x32 frames */
#include "res/roofs.inc"        /* generated: roofs_tiles[], roofs_pal[], roofs_map[], each with _end */
#include "res/kit.inc"          /* generated: kit_tiles[], kit_pal[], each with _end */

/** @brief The level's tilemap, tile definitions and objects (opensnes-level) */
#include "res/rooftops.inc"     /* generated by opensnes-level: rooftops_BG1_map[], rooftops_tiledef[], rooftops_tileattr[], rooftops_objects[] */

/*============================================================================
 * Game State
 *============================================================================*/

/** @brief First walk frame in Kit's sheet (frames 4-11, four 32x32 frames a row) */
#define FRAME_WALK 4

/** @brief The roofs' surface: row 22 of the map */
#define ROOF_Y (22 * 8)

/** @brief Kit X position in map pixels */
u16 xloc;

/** @brief Kit Y position in map pixels (the top of his 32x32 frame) */
u16 yloc;

/** @brief Current walk frame index (0-7) */
u16 frameidx;

/** @brief Current sprite tile number */
u16 frame;

/** @brief Horizontal flip flag (1 = facing left) */
u16 flipx;

/** @brief Animation counter (one walk frame every 4 frames of movement) */
u16 flip;

/**
 * @brief OAM tile number of frame f of Kit's sheet.
 *
 * The converter lays the sheet's 32x32 blocks out four to a 128-pixel row of
 * OBJ VRAM: block f starts at tile (f % 4) * 4 + (f / 4) * 64.
 */
static u16 kit_tile(u16 f) {
    return (u16)((f & 3) * 4 + (f >> 2) * 64);
}

/**
 * @brief Entry point — scrolling map with Kit walking on it
 * @return Never returns (infinite game loop)
 */
int main(void) {
    u16 pad;

    consoleInit();

    /* Load the roofs' tiles to VRAM $2000, palette to CGRAM */
    bgInitTileSet(0, roofs_tiles, roofs_pal, 0,
                  roofs_tiles_end - roofs_tiles,
                  roofs_pal_end - roofs_pal,
                  BG_16COLORS, 0x2000);

    /* Map engine requires tilemap at $6800, SC_64x32 */
    bgSetMapPtr(0, 0x6800, SC_64x32);

    /* Mode 1, BG1 + sprites */
    setMode(BG_MODE1, 0);
    setMainScreen(LAYER_BG1 | LAYER_OBJ);

    /* Load Kit's sheet to VRAM $0000, palette to CGRAM 128 */
    oamInitGfxSet(kit_tiles, kit_tiles_end - kit_tiles,
                  kit_pal, kit_pal_end - kit_pal,
                  0, 0x0000, OBJ_SIZE16_L32);
    oamSetSize(0, OBJ_LARGE);           /* Kit is a 32x32 sprite */

    /* Load map (screen still off — no garbage) */
    mapLoad(rooftops_BG1_map, rooftops_tiledef, rooftops_tileattr);

    /* Initial position: near left edge, standing on the roofs (his feet
     * are on row 30 of his frame) */
    xloc = 16 * 8;
    yloc = ROOF_Y - 30;
    frameidx = 0;
    frame = kit_tile(FRAME_WALK);
    flipx = 0;
    flip = 0;

    mapUpdateCamera(xloc, yloc);

    /* Screen on — mapLoad flushes VRAM internally */
    setScreenOn();

    /* Main loop */
    while (1) {
        pad = padHeld(0);

        /* Move left */
        if (pad & KEY_LEFT) {
            if (xloc > 0) xloc--;
            flipx = 1;
            mapUpdateCamera(xloc, yloc);
            if ((flip++ & 3) == 3) {
                frameidx = (frameidx + 1) & 7;
                frame = kit_tile(FRAME_WALK + frameidx);
            }
        }

        /* Move right */
        if (pad & KEY_RIGHT) {
            xloc++;
            flipx = 0;
            mapUpdateCamera(xloc, yloc);
            if ((flip++ & 3) == 3) {
                frameidx = (frameidx + 1) & 7;
                frame = kit_tile(FRAME_WALK + frameidx);
            }
        }

        /* Draw Kit relative to camera position
         * oamSet(id, x, y, tile, palette, priority, flags)
         * flags bit 6 = horizontal flip */
        oamSet(0, xloc - mapGetCameraX(), yloc - mapGetCameraY(), frame, 0, 3,
               flipx ? OBJ_FLIPX : 0);

        /* Update map engine */
        mapUpdate();
        WaitForVBlank();
        mapVblank();
    }

    return 0;
}
