/**
 * @file main.c
 * @ingroup examples
 * @brief One-shot sound effects from WAV files, converted by the build.
 *
 * The smallest "press a button, hear a sound" example, and a showcase of the
 * settings-file build: `res/blip.wav` and `res/coin.wav` are plain PCM WAV
 * files with a `.wav.toml` beside each (`tool = "opensnes-sample"`); the
 * build converts them with opensnes-sample and links the .brr — no .brr is
 * committed, they are generated on demand like a .pic from a .png.
 *
 * See docs/tutorials/audio_samples.md ("One-shot samples from WAV").
 *
 * @par SNES Concepts
 * - BRR samples: the S-DSP plays BRR, nothing else
 * - audioLoadSample() uploads a sample to the SPC700 once; audioPlaySample()
 *   triggers it on demand
 * - Edge-triggered input: padPressed() fires once per press
 *
 * @par What to Observe
 * - Press A for a blip, B for a coin; one press, one sound
 *
 * @par Modules Used
 * console, dma, audio, input, background, text
 *
 * @see audio.h — audioLoadSample / audioPlaySample
 */
#include <snes.h>
#include <snes/audio.h>
#include <snes/input.h>
#include <snes/text.h>

/* The .brr samples the build converted from the res/ WAV files, with their symbols */
#include "res/blip.h"   /* generated by opensnes-sample: blip_brr[], blip_brr_end[], the size */
#include "res/coin.h"

#define SMP_BLIP 0
#define SMP_COIN 1

int main(void) {
    textModeInit();
    audioInit();
    setColor(0, RGB(2, 4, 12));

    /* Load each sample once into the SPC700; 0 loop point = one-shot. */
    audioLoadSample(SMP_BLIP, blip_brr, (u16)(blip_brr_end - blip_brr), 0);
    audioLoadSample(SMP_COIN, coin_brr, (u16)(coin_brr_end - coin_brr), 0);

    textPrintAt(6, 4, "SFX FROM WAV");
    textPrintAt(4, 8, "A - BLIP");
    textPrintAt(4, 10, "B - COIN");
    textPrintAt(3, 16, "BUILT FROM RES/*.WAV");

    WaitForVBlank();
    setScreenOn();

    while (1) {
        WaitForVBlank();

        u16 keys = padPressed(0);   /* edge-triggered: one play per press */
        if (keys & KEY_A)
            audioPlaySample(SMP_BLIP);
        if (keys & KEY_B)
            audioPlaySample(SMP_COIN);
    }
    return 0;
}
