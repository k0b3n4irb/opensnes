/**
 * @file main.c
 * @brief End-to-end Aseprite sprite pipeline: art + timeline → animated metasprite
 * @ingroup examples
 *
 * This example animates a 32×48 hero metasprite whose every byte of data is
 * machine-generated from a single Aseprite project — no hand-authored frame
 * tables, no hand-typed animation clips. It is the working reference for the
 * two-tool sprite pipeline:
 *
 *   hero.aseprite ─┬─ gfx4snes -P    → hero.pic/.pal + res/hero_meta.inc
 *                  │                   (tiles, palette, metasprite pointer table)
 *                  └─ aseprite2snes  → res/hero_anim.h
 *                                      (one AnimClip per Aseprite tag)
 *
 * gfx4snes owns the pixels and the metasprite geometry; aseprite2snes owns the
 * timeline (tags, per-frame durations, direction) that indexes it. They meet at
 * the frame value: a clip's frame @c i selects @c hero_metasprites[i], resolved
 * inline by @c animTickMeta().
 *
 * The artist authored two tags in Aseprite — @c walk (forward loop) and
 * @c wave (ping-pong) — with per-frame millisecond durations. aseprite2snes
 * converted those to ticks and folded the ping-pong into the frame order; press
 * A to toggle between the two generated clips.
 *
 * @par SNES Concepts
 * - Metasprite composition from multiple OAM entries (oamDrawMeta)
 * - The anim.h player driving a metasprite via animTickMeta()
 * - OBJSEL size mode + OBJ VRAM base for 16×16 hardware sprites
 * - Sprite palette at CGRAM 128 (OBJ_CGRAM_BASE)
 *
 * @par What to Observe
 * - A hero walks in place (4-frame cycle, per-frame timing from Aseprite)
 * - Press A to toggle to the ping-pong "wave" clip and back
 * - The text label shows which generated clip is playing
 *
 * @par Modules Used
 * console, sprite, dma, text, text4bpp, background, input, anim
 *
 * @see sprite.h, anim.h, dma.h, input.h, tools/aseprite2snes
 */

#include <snes.h>
#include <snes/anim.h>

/**
 * @brief Metasprite pointer table generated by gfx4snes -P.
 *
 * Defines hero_metasprite0..3 (each a MetaspriteItem[] terminated by
 * METASPR_TERM) plus hero_metasprites[4], the pointer table the animation
 * clips index. One entry per cell of the hero.png sheet, in sheet order.
 */
#include "res/hero_meta.inc"

/**
 * @brief Animation clips generated by aseprite2snes from res/hero.json.
 *
 * Defines hero_walk / hero_wave (AnimClip), the hero_anims[] pointer table and
 * the HERO_ANIM_* index enum. Frame values index hero_metasprites[] above.
 */
#include "res/hero_anim.h"

/** @brief 4bpp hero tiles (res/hero.pic, incbin'd in data.asm) */
extern u8 hero_til[], hero_tilend[];
/** @brief Hero sprite palette, 16 colours (res/hero.pal) */
extern u8 hero_pal[];

/** @brief OBJ VRAM word address for the hero tiles (OBJSEL name base = 0) */
#define VRAM_HERO   0x0000
/** @brief BG1 font tiles (4bpp, high VRAM so they clear the OBJ region) */
#define VRAM_FONT   0x4000
/** @brief BG1 text tilemap */
#define VRAM_TEXT   0x6800

/** @brief On-screen X of the metasprite origin (32-wide sprite, centred) */
#define HERO_X      112
/** @brief On-screen Y of the metasprite origin (48-tall sprite, centred) */
#define HERO_Y      88

/** @brief Animation player driving the hero metasprite */
static AnimPlayer hero_player = ANIM_PLAYER_INIT;

/**
 * @brief Print the label for the currently playing generated clip.
 * @param idx One of HERO_ANIM_WALK / HERO_ANIM_WAVE.
 */
static void drawLabel(u16 idx) {
    textClearRect(2, 3, 28, 1);
    /* if/else, not `textPrintAt(2, 3, idx ? "A" : "B")`: a ternary yielding a
     * string literal currently miscompiles (the far pointer's bank byte is
     * dropped, so the callee reads garbage). See
     * .claude/notes/tech/ternary_addr_const_bank_drop.md. */
    if (idx == HERO_ANIM_WALK)
        textPrintAt(2, 3, "Clip: WALK  (forward loop)");
    else
        textPrintAt(2, 3, "Clip: WAVE  (ping-pong)");
}

/**
 * @brief Entry point: animate the generated metasprite, toggle clips on A.
 * @return Never returns (infinite loop).
 */
int main(void) {
    consoleInit();
    setMode(BG_MODE1, 0);

    /* BG1 text tiles/map sit above the OBJ region so they never overlap. */
    bgSetGfxPtr(0, VRAM_FONT);
    bgSetMapPtr(0, VRAM_TEXT, SC_32x32);
    textLoadFont4bpp(VRAM_FONT);
    textInit(VRAM_TEXT, 0, 0);

    /* Font palette: BG palette 0, colour 0 black, colour 1 white. */
    setColor(0, RGB(0, 0, 0));
    setColor(1, RGB(31, 31, 31));

    /* All VRAM/CGRAM writes happen here, under the boot force-blank. */
    dmaCopyVram(hero_til, VRAM_HERO, (u16)(hero_tilend - hero_til));
    dmaCopyCGram(hero_pal, OBJ_CGRAM_BASE, PALETTE_16_SIZE);

    /* 16×16 hardware sprites (small size of the 16/32 pair), OBJ base $0000. */
    REG_OBJSEL = OBJ_SIZE_TO_REG(OBJ_SIZE16_L32);
    oamClear();

    setMainScreen(TM_BG1 | TM_OBJ);

    textPrintAt(2, 1,  "aseprite2snes + gfx4snes -P");
    textPrintAt(2, 5,  "Press A: toggle clip");
    textPrintAt(2, 24, "Frames + timing from hero.json");

    u16 current = HERO_ANIM_WALK;
    animPlay(&hero_player, hero_anims[current]);
    drawLabel(current);

    /* First frame drawn during force blank, then screen on. */
    oamDrawMeta(0, HERO_X, HERO_Y,
                animTickMeta(&hero_player, hero_metasprites), 0, 0, OBJ_SMALL);
    WaitForVBlank();
    setScreenOn();

    while (1) {
        u16 pressed = padPressed(0);

        if (pressed & KEY_A) {
            current ^= 1;                        /* toggle WALK <-> WAVE */
            animPlay(&hero_player, hero_anims[current]);
            drawLabel(current);
        }

        /* animTickMeta advances the player one tick and yields this frame's
         * MetaspriteItem*, which oamDrawMeta expands into 6 OAM entries. */
        oamDrawMeta(0, HERO_X, HERO_Y,
                    animTickMeta(&hero_player, hero_metasprites), 0, 0, OBJ_SMALL);
        WaitForVBlank();
    }

    return 0;
}
