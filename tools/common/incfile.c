/*
 * incfile.c — the two glue files a converted graphic ships with, in the
 * naming of the lib's asset.h (2026-10-05):
 *
 *   <stem>.inc      a C header: #include <snes/asset.h> and a ready
 *                   DECLARE_BG_ASSET / DECLARE_GFX_ASSET (the externs plus a
 *                   static const BgAsset / GfxAsset the game hands to
 *                   bgLoad() / gfxLoad()), or plain externs when no macro
 *                   fits (Mode 7, an unusual map size, no palette)
 *   <stem>_data.as  the .incbin fragment assets_gen.asm includes: one
 *                   ASSET_SECTION per blob — <name>_tiles / <name>_tiles_end,
 *                   <name>_pal / <name>_pal_end, <name>_map / <name>_map_end;
 *                   a blob above 32 KB is cut in parts (<name>_tiles_1, ...)
 *                   because a section lives in one bank
 *
 * gfx4snes wrote <name>_til / <name>_tilend, <name>_pal / <name>_palend,
 * <name>_map / <name>_mapend and externs of `unsigned char` scalars; the
 * family writes what asset.h expects, so `#include "res/town.inc"` then
 * `bgLoad(0, &town, 0, 0x4000, 0x0000)` is the whole load.
 */
#include "incfile.h"

#include <stdio.h>
#include <string.h>
#include <sys/stat.h>

#define BANK_BYTES 32768L

static long file_size(const char *path)
{
    struct stat st;
    return stat(path, &st) == 0 ? (long)st.st_size : -1;
}

/* How many 32 KB parts a blob needs: an ASSET_SECTION lives in one bank. */
static int parts_of(const char *path)
{
    long n = file_size(path);
    return n <= BANK_BYTES ? 1 : (int)((n + BANK_BYTES - 1) / BANK_BYTES);
}

/* One blob: its own ASSET_SECTION, or one per 32 KB part (<label>, <label>_1, ...). */
static void write_blob(FILE *f, const char *name, const char *what, const char *path)
{
    int parts = parts_of(path);
    for (int i = 0; i < parts; i++) {
        char label[300];
        if (i == 0) snprintf(label, sizeof label, "%s_%s", name, what);
        else        snprintf(label, sizeof label, "%s_%s_%d", name, what, i);
        fprintf(f, "ASSET_SECTION \"%s\"\n%s:\n", label, label);
        if (parts == 1) fprintf(f, ".incbin \"%s\"\n", path);
        else {
            long left = file_size(path) - i * BANK_BYTES;
            fprintf(f, ".incbin \"%s\" skip %ld read %ld\n", path, i * BANK_BYTES, left < BANK_BYTES ? left : BANK_BYTES);
        }
        fprintf(f, "%s_end:\n.ENDS\n\n", label);
    }
}

static const char *color_mode(int bpp)
{
    return bpp == 2 ? "BG_4COLORS" : bpp == 8 ? "BG_256COLORS" : "BG_16COLORS";
}

static const char *map_size(int blocks_x, int blocks_y)
{
    if (blocks_x == 32 && blocks_y == 32) return "SC_32x32";
    if (blocks_x == 64 && blocks_y == 32) return "SC_64x32";
    if (blocks_x == 32 && blocks_y == 64) return "SC_32x64";
    if (blocks_x == 64 && blocks_y == 64) return "SC_64x64";
    return NULL;
}

int incfile_write(const char *outbase, const char *name, const incfile_spec *spec, char *err, size_t errlen)
{
    char path[1100];
    const char *tiles_ext = spec->mode7 ? ".pc7" : ".pic", *map_ext = spec->mode7 ? ".mp7" : ".map";
    char tiles_path[1100], map_path[1100], pal_path[1100];
    snprintf(tiles_path, sizeof tiles_path, "%s%s", outbase, tiles_ext);
    snprintf(map_path, sizeof map_path, "%s%s", outbase, map_ext);
    snprintf(pal_path, sizeof pal_path, "%s.pal", outbase);
    int tiles_parts = parts_of(tiles_path), map_parts = spec->has_map ? parts_of(map_path) : 1;
    int split = tiles_parts > 1 || map_parts > 1;

    /* ---- the header */
    snprintf(path, sizeof path, "%s.inc", outbase);
    FILE *f = fopen(path, "w");
    if (!f) { snprintf(err, errlen, "cannot write %s", path); return -1; }
    fprintf(f, "/* %s.inc — generated by %s; do not edit. The data labels live in %s_data.as,\n"
               " * which the build gathers into assets_gen.asm (docs/tools/CONVENTIONS.md). */\n"
               "#ifndef ASSET_%s_INC\n#define ASSET_%s_INC\n\n#include <snes/asset.h>\n\n",
            name, spec->generator, name, name, name);
    const char *ms = spec->has_map ? map_size(spec->map_blocks_x, spec->map_blocks_y) : NULL;
    if (split) {
        fprintf(f, "/* a blob larger than one 32 KB bank is written in parts, one ASSET_SECTION each:\n"
                   " * %s_tiles, %s_tiles_1, ... (each with _end) — load them with one dmaCopyVram per part */\n", name, name);
        for (int i = 0; i < tiles_parts; i++)
            i == 0 ? fprintf(f, "extern const u8 %s_tiles[], %s_tiles_end[];\n", name, name)
                   : fprintf(f, "extern const u8 %s_tiles_%d[], %s_tiles_%d_end[];\n", name, i, name, i);
        if (spec->has_pal) fprintf(f, "extern const u8 %s_pal[], %s_pal_end[];\n", name, name);
        for (int i = 0; spec->has_map && i < map_parts; i++)
            i == 0 ? fprintf(f, "extern const u8 %s_map[], %s_map_end[];\n", name, name)
                   : fprintf(f, "extern const u8 %s_map_%d[], %s_map_%d_end[];\n", name, i, name, i);
    } else if (spec->lz) {
        fprintf(f, "/* LZ77-compressed tiles: lzssDecodeVram(%s_tiles, vram_addr); no asset bundle, bgLoad() would copy the compressed bytes */\n", name);
        fprintf(f, "extern const u8 %s_tiles[], %s_tiles_end[];\n", name, name);
        if (spec->has_pal) fprintf(f, "extern const u8 %s_pal[], %s_pal_end[];\n", name, name);
        if (spec->has_map) fprintf(f, "extern const u8 %s_map[], %s_map_end[];\n", name, name);
    } else if (spec->has_map && spec->has_pal && !spec->mode7 && ms) {
        fprintf(f, "/* tileset + palette + %dx%d tilemap: bgLoad(bg, &%s, palette_slot, tiles_vram, map_vram) */\n"
                   "DECLARE_BG_ASSET(%s, %s, %s);\n", spec->map_blocks_x, spec->map_blocks_y, name, name, color_mode(spec->bpp), ms);
    } else if (!spec->has_map && spec->has_pal && !spec->mode7) {
        fprintf(f, "/* tileset + palette: gfxLoad(bg, &%s, palette_slot, tiles_vram), or the arrays below with dmaCopyVram / dmaCopyCGram */\n"
                   "DECLARE_GFX_ASSET(%s, %s);\n", name, name, color_mode(spec->bpp));
    } else {
        fprintf(f, "/* %s: the arrays, for dmaCopyVram / dmaCopyCGram */\n", spec->mode7 ? "Mode 7 (packed tiles, one byte per map entry)" : "no asset bundle fits this shape");
        fprintf(f, "extern const u8 %s_tiles[], %s_tiles_end[];\n", name, name);
        if (spec->has_pal) fprintf(f, "extern const u8 %s_pal[], %s_pal_end[];\n", name, name);
        if (spec->has_map) fprintf(f, "extern const u8 %s_map[], %s_map_end[];\n", name, name);
    }
    if (spec->has_meta)
        fprintf(f, "\n/* the metasprite table: #include \"%s_meta.inc\" once, in the file that draws it */\n", name);
    fprintf(f, "\n#endif\n");
    fclose(f);

    /* ---- the .incbin fragment */
    snprintf(path, sizeof path, "%s_data.as", outbase);
    f = fopen(path, "w");
    if (!f) { snprintf(err, errlen, "cannot write %s", path); return -1; }
    fprintf(f, "; %s_data.as — generated by %s; one ASSET_SECTION per blob, .include it from assets_gen.asm (the build does)\n\n", name, spec->generator);
    write_blob(f, name, "tiles", tiles_path);
    if (spec->has_map) write_blob(f, name, "map", map_path);
    if (spec->has_pal) write_blob(f, name, "pal", pal_path);
    fclose(f);
    return 0;
}
