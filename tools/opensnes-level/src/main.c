/*
 * opensnes-level — Tiled levels to SNES map data (the 1.x successor of
 * tmx2snes; its converter is linked here as a library, so the bytes are
 * its own).
 *
 *   opensnes-level convert --tileset FILE [--entities] [--quadrant] [--collision] [--out DIR] [--save] [--json] <level.tmj>...
 *   opensnes-level inspect [--json] <level.tmj>...
 *
 * `convert` turns a Tiled JSON map drawn against a tileset converted by
 * opensnes-tileset into what the `map` and `object` modules load: one
 * <layer>.m16 per tile layer, <stem>.b16 (tile attributes), <stem>.t16
 * (tile properties), <stem>.o16 (the Entities layer), plus the <stem>.inc /
 * <stem>_data.as glue the build assembles.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "cli.h"
#include "incfile.h"
#include "level.h"

static int split_input(cli_ctx *ctx, const char *in, char *base, size_t n)
{
    const char *slash = strrchr(in, '/');
    const char *dot = strrchr(slash ? slash + 1 : in, '.');
    if (!dot) { cli_error(ctx, in, "no extension — a Tiled JSON map (.tmj or .json) is expected"); return 0; }
    if (strcmp(dot, ".tmj") && strcmp(dot, ".json") && strcmp(dot, ".TMJ") && strcmp(dot, ".JSON")) {
        cli_error(ctx, in, "%s is not a Tiled JSON map (.tmj / .json): export the map as JSON in Tiled", dot); return 0;
    }
    snprintf(base, n, "%.*s", (int)(dot - in), in);
    return 1;
}

/* a layer name as a C identifier piece ("BG 1" -> "BG_1") */
static void ident_of(const char *s, char *out, size_t n)
{
    size_t i = 0;
    for (; *s && i + 1 < n; s++) {
        char c = *s;
        out[i++] = ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')) ? c : '_';
    }
    out[i] = '\0';
}

/* the glue: <outbase>.inc (externs) and <outbase>_data.as (one ASSET_SECTION per blob) */
static int write_glue(cli_ctx *ctx, const char *in, const char *outbase, const char *ident, const level_result *r, int quadrant, int collision)
{
    char path[1200], dir[1200], lname[64];
    const char *slash = strrchr(outbase, '/');
    snprintf(dir, sizeof dir, "%.*s", slash ? (int)(slash - outbase + 1) : 0, outbase);

    snprintf(path, sizeof path, "%s.inc", outbase);
    FILE *f = fopen(path, "w");
    if (!f) { cli_error(ctx, in, "cannot write %s", path); return CLI_IO; }
    fprintf(f, "/* %s.inc — generated by %s %s; do not edit. The data labels live in %s_data.as,\n"
               " * which the build gathers into assets_gen.asm (docs/tools/CONVENTIONS.md). */\n"
               "#ifndef ASSET_%s_INC\n#define ASSET_%s_INC\n\n#include <snes/types.h>\n\n",
            ident, ctx->tool->name, ctx->tool->version, ident, ident, ident);
    fprintf(f, "/* the map module: mapLoad(%s_%s_map, %s_tiledef, %s_tileattr)", ident, r->nlayers ? (ident_of(r->layer_name[0], lname, sizeof lname), lname) : "LAYER", ident, ident);
    if (r->object_count >= 0) fprintf(f, "; the object module: objLoadObjects(%s_objects)", ident);
    fprintf(f, " */\n");
    for (int i = 0; i < r->nlayers; i++) {
        ident_of(r->layer_name[i], lname, sizeof lname);
        fprintf(f, "extern const u8 %s_%s_map[], %s_%s_map_end[];   /* %s.m16: %dx%d tiles, 6-byte header then one word per cell */\n",
                ident, lname, ident, lname, r->layer_name[i], r->map_width, r->map_height);
        if (quadrant)  fprintf(f, "extern const u8 %s_%s_quad[], %s_%s_quad_end[];   /* %s.q16: the four 32x32 pages, ready for VRAM */\n", ident, lname, ident, lname, r->layer_name[i]);
        if (collision) fprintf(f, "extern const u8 %s_%s_cells[], %s_%s_cells_end[];   /* %s.c16: one collision byte per cell, for collideTile() */\n", ident, lname, ident, lname, r->layer_name[i]);
    }
    fprintf(f, "extern const u8 %s_tileattr[], %s_tileattr_end[];   /* .b16: one word per tileset tile, the `attribute` property (collision) */\n", ident, ident);
    fprintf(f, "extern const u8 %s_tiledef[], %s_tiledef_end[];     /* .t16: one word per tileset tile, its VRAM tile with palette and priority */\n", ident, ident);
    if (r->object_count >= 0)
        fprintf(f, "extern const u8 %s_objects[], %s_objects_end[];   /* .o16: %d entities (x, y, type, minx, maxx), $FFFF-terminated */\n", ident, ident, r->object_count);
    fprintf(f, "\n#endif\n");
    fclose(f);

    snprintf(path, sizeof path, "%s_data.as", outbase);
    f = fopen(path, "w");
    if (!f) { cli_error(ctx, in, "cannot write %s", path); return CLI_IO; }
    fprintf(f, "; %s_data.as — generated by %s %s; one ASSET_SECTION per blob, .include it from assets_gen.asm (the build does)\n\n", ident, ctx->tool->name, ctx->tool->version);
    char blob[1300], what[80];
    for (int i = 0; i < r->nlayers; i++) {
        ident_of(r->layer_name[i], lname, sizeof lname);
        snprintf(blob, sizeof blob, "%s%s.m16", dir, r->layer_name[i]); snprintf(what, sizeof what, "%s_map", lname); incfile_write_blob(f, ident, what, blob);
        if (quadrant)  { snprintf(blob, sizeof blob, "%s%s.q16", dir, r->layer_name[i]); snprintf(what, sizeof what, "%s_quad", lname); incfile_write_blob(f, ident, what, blob); }
        if (collision) { snprintf(blob, sizeof blob, "%s%s.c16", dir, r->layer_name[i]); snprintf(what, sizeof what, "%s_cells", lname); incfile_write_blob(f, ident, what, blob); }
    }
    snprintf(blob, sizeof blob, "%s.b16", outbase); incfile_write_blob(f, ident, "tileattr", blob);
    snprintf(blob, sizeof blob, "%s.t16", outbase); incfile_write_blob(f, ident, "tiledef", blob);
    if (r->object_count >= 0) { snprintf(blob, sizeof blob, "%s.o16", outbase); incfile_write_blob(f, ident, "objects", blob); }
    fclose(f);
    return CLI_OK;
}

/* --------------------------------------------------------------- convert */
static const cli_opt convert_opts[] = {
    { "tileset", 0, CLI_STR, "FILE", "the tileset's .map written by opensnes-tileset: the tile table the level was drawn against (needed for .t16)", NULL },
    { "entities", 0, CLI_FLAG, NULL, "also write <stem>_entities.inc: the Entities layer as C defines (<TYPE>_COUNT, _FIELDS, _TABLE)", NULL },
    { "quadrant", 0, CLI_FLAG, NULL, "also write <layer>.q16: the 64x64 map in the PPU's four 32x32 pages, palette and priority folded in", NULL },
    { "collision", 0, CLI_FLAG, NULL, "also write <layer>.c16: one collision byte per map cell, what collideTile() reads", NULL },
    CLI_OPT_OUT,
    CLI_OPT_SAVE,
};

static int convert_one(cli_ctx *ctx, const char *in)
{
    int rc = cli_load_settings(ctx, in);
    if (rc != CLI_OK) return rc;
    char inbase[1024], outbase[1024], tilesetbuf[1100], hdr[1100], ident[256], err[1200], generator[64];
    if (!split_input(ctx, in, inbase, sizeof inbase)) return CLI_REFUSED;
    if (cli_output_path(ctx, in, "", outbase, sizeof outbase) != CLI_OK) return CLI_IO;
    const char *tileset = cli_path(ctx, "tileset", tilesetbuf, sizeof tilesetbuf);
    if (!tileset) { cli_error(ctx, in, "no --tileset: the .map opensnes-tileset wrote for the tileset the level uses (tileset = \"town.map\" in %s.toml)", in); return CLI_REFUSED; }
    int entities = cli_has(ctx, "entities"), quadrant = cli_has(ctx, "quadrant"), collision = cli_has(ctx, "collision");
    cli_ident(in, ident, sizeof ident);
    snprintf(generator, sizeof generator, "%s %s", ctx->tool->name, ctx->tool->version);
    snprintf(hdr, sizeof hdr, "%s_entities.inc", outbase);
    level_opts opts = { entities, quadrant, collision, 0, generator, hdr };
    level_result res;
    if (level_convert(in, tileset, outbase, &opts, &res, NULL, NULL, err, sizeof err) != 0) {
        cli_error(ctx, in, "%s", err);
        return CLI_REFUSED;
    }
    if ((rc = write_glue(ctx, in, outbase, ident, &res, quadrant, collision)) != CLI_OK) return rc;
    if (cli_has(ctx, "save") && (rc = cli_save_settings(ctx, in)) != CLI_OK) return rc;
    if (ctx->json) {
        cli_json_object(ctx, NULL);
        cli_json_str(ctx, "input", in);
        cli_json_int(ctx, "width", res.map_width); cli_json_int(ctx, "height", res.map_height);
        cli_json_int(ctx, "tileset_tiles", res.tilecount); cli_json_int(ctx, "objects", res.object_count < 0 ? 0 : res.object_count);
        cli_json_array(ctx, "layers");
        for (int i = 0; i < res.nlayers; i++) { cli_json_object(ctx, NULL); cli_json_str(ctx, "name", res.layer_name[i]); cli_json_int(ctx, "map_bytes", 6 + 2L * res.map_width * res.map_height); cli_json_close(ctx); }
        cli_json_close(ctx);
        cli_json_array(ctx, "outputs");
        char path[1200];
        const char *dir_end = strrchr(outbase, '/');
        for (int i = 0; i < res.nlayers; i++) {
            snprintf(path, sizeof path, "%.*s%s.m16", dir_end ? (int)(dir_end - outbase + 1) : 0, outbase, res.layer_name[i]);
            cli_json_object(ctx, NULL); cli_json_str(ctx, "path", path); cli_json_str(ctx, "kind", "map"); cli_json_close(ctx);
        }
        const char *exts[] = { ".b16", ".t16", res.object_count >= 0 ? ".o16" : NULL, ".inc", "_data.as", entities && res.object_count >= 0 ? "_entities.inc" : NULL };
        const char *kinds[] = { "tile_attributes", "tile_properties", "objects", "header", "asm", "entities_header" };
        for (int i = 0; i < 6; i++) {
            if (!exts[i]) continue;
            snprintf(path, sizeof path, "%s%s", outbase, exts[i]);
            cli_json_object(ctx, NULL); cli_json_str(ctx, "path", path); cli_json_str(ctx, "kind", kinds[i]); cli_json_close(ctx);
        }
        cli_json_close(ctx);
        cli_json_close(ctx);
    } else if (!ctx->quiet) {
        printf("%s: %s -> %d layer%s of %dx%d tiles (%s.m16), %s.b16 + .t16 (%d tiles)%s%s\n", ctx->tool->name, in,
               res.nlayers, res.nlayers == 1 ? "" : "s", res.map_width, res.map_height, res.nlayers ? res.layer_name[0] : "?",
               outbase, res.tilecount, res.object_count >= 0 ? ", .o16" : "", entities && res.object_count >= 0 ? ", _entities.inc" : "");
    }
    return CLI_OK;
}

static int run_convert(cli_ctx *ctx)
{
    int worst = CLI_OK;
    if (ctx->json) { cli_json_begin(ctx); cli_json_array(ctx, "levels"); }
    for (int i = 0; i < ctx->nargs; i++) {
        int rc = convert_one(ctx, ctx->args[i]);
        if (rc != CLI_OK && ctx->json) { cli_json_object(ctx, NULL); cli_json_str(ctx, "input", ctx->args[i]); cli_json_int(ctx, "error", rc); cli_json_close(ctx); }
        if (rc > worst) worst = rc;
    }
    if (ctx->json) cli_json_end(ctx);
    return worst;
}

/* --------------------------------------------------------------- inspect */
static int run_inspect(cli_ctx *ctx)
{
    int worst = CLI_OK;
    if (ctx->json) { cli_json_begin(ctx); cli_json_array(ctx, "levels"); }
    for (int i = 0; i < ctx->nargs; i++) {
        const char *in = ctx->args[i];
        char inbase[1024], err[1200];
        if (!split_input(ctx, in, inbase, sizeof inbase)) { worst = CLI_REFUSED; continue; }
        level_opts opts = { 0, 0, 0, 1, NULL, NULL };
        level_result res;
        if (level_convert(in, NULL, inbase, &opts, &res, NULL, NULL, err, sizeof err) != 0) {
            cli_error(ctx, in, "%s", err); worst = CLI_REFUSED; continue;
        }
        long map_bytes = 6 + 2L * res.map_width * res.map_height;
        if (ctx->json) {
            cli_json_object(ctx, NULL); cli_json_str(ctx, "input", in);
            cli_json_int(ctx, "width", res.map_width); cli_json_int(ctx, "height", res.map_height);
            cli_json_int(ctx, "tileset_tiles", res.tilecount); cli_json_int(ctx, "objects", res.object_count < 0 ? 0 : res.object_count);
            cli_json_int(ctx, "map_bytes_per_layer", map_bytes);
            cli_json_array(ctx, "layers");
            for (int k = 0; k < res.nlayers; k++) { cli_json_object(ctx, NULL); cli_json_str(ctx, "name", res.layer_name[k]); cli_json_close(ctx); }
            cli_json_close(ctx);
            cli_json_close(ctx);
        } else {
            printf("%s: %dx%d tiles of %dx%d px, %d tile layer%s (", in, res.map_width, res.map_height, res.tilewidth, res.tileheight, res.nlayers, res.nlayers == 1 ? "" : "s");
            for (int k = 0; k < res.nlayers; k++) printf("%s%s", k ? ", " : "", res.layer_name[k]);
            printf("), %ld bytes of map each, tileset of %d tiles, %d entit%s\n", map_bytes, res.tilecount,
                   res.object_count < 0 ? 0 : res.object_count, res.object_count == 1 ? "y" : "ies");
        }
    }
    if (ctx->json) cli_json_end(ctx);
    return worst;
}

static const cli_cmd cmds[] = {
    { "convert", "Tiled JSON map -> <layer>.m16, .b16, .t16, .o16 for the map and object modules, and the .inc / _data.as the build assembles",
      convert_opts, CLI_N(convert_opts), "convert res/town.tmj --tileset res/tiles.map --entities --save", 1, run_convert },
    { "inspect", "what a level holds: size, layers, tileset tiles, entities, bytes of map", NULL, 0, "inspect res/*.tmj", 1, run_inspect },
};

int main(int argc, char **argv)
{
    static const cli_tool tool = {
        "opensnes-level", TOOL_VERSION, "Tiled levels -> map, tile attributes, objects for the SNES map engine", cmds, CLI_N(cmds),
    };
    return cli_main(&tool, argc, argv);
}
