/*
 * opensnes-sample — WAV → BRR samples for the SNES DSP (the 1.x successor
 * of wav2brr, same encoder, same bytes).
 *
 *   opensnes-sample encode  [--loop START END] [--out DIR] [--save] [--json] <input.wav>...
 *   opensnes-sample inspect [--json] <file.wav | file.brr>...
 *
 * The encoder is smconv's (tools/smconv/src/brr.c, (C) 2009 Mukunda
 * Johnson): BRR block compression, 16-sample padding, loop unrolling and
 * resampling, overflow-driven amplitude backoff. A .brr from here is byte
 * for byte what wav2brr wrote and what a soundbank carries.
 *
 * Outputs, beside the input or in --out: <stem>.brr and <stem>.h (the
 * sizes and the loop offset as macros, so the game never hard-codes them).
 * Settings beside the asset: <input.wav>.toml, written by --save.
 */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "cli.h"
#include "brr.h"   /* tools/smconv/src */
#include "wav.h"

/* The DSP plays BRR at 32 kHz whatever the source said; a sample above
 * that comes out lower and slower by the ratio of the rates. */
#define DSP_RATE 32000
#define BRR_BLOCK 9       /* bytes per block of 16 samples */

/* Read a WAV from disk through the in-memory parser (wav.c); says why not. */
static int wav_read(cli_ctx *ctx, const char *path, wav_t *w)
{
    size_t fsz = 0;
    unsigned char *buf = cli_read_file(ctx, path, &fsz);
    if (!buf) return CLI_IO;
    char why[160];
    int ok = wav_parse(buf, fsz, w, why, sizeof why);
    free(buf);
    if (!ok) { cli_error(ctx, path, "%s", why); return CLI_REFUSED; }
    return CLI_OK;
}

/* ---------------------------------------------------------------- encode */

static const cli_opt encode_opts[] = {
    { "loop", 0, CLI_INT2, "START END", "loop between two sample indices (default: one-shot)", NULL },
    CLI_OPT_OUT,
    CLI_OPT_SAVE,
};

static int encode_one(cli_ctx *ctx, const char *input)
{
    int rc = cli_load_settings(ctx, input);
    if (rc != CLI_OK) return rc;

    wav_t w;
    rc = wav_read(ctx, input, &w);
    if (rc != CLI_OK) return rc;

    int loop_start = 0, loop_end = 0;
    int has_loop = cli_int2(ctx, "loop", &loop_start, &loop_end);
    if (has_loop && (loop_start < 0 || loop_end > w.count || loop_start >= loop_end)) {
        cli_error(ctx, input, "--loop %d %d is out of range — the file has %d samples, START < END",
                  loop_start, loop_end, w.count);
        free(w.pcm);
        return CLI_REFUSED;
    }

    u8 *brr = NULL;
    int brr_len = 0, brr_loop = 0;
    double tuning = 1.0;
    brr_encode(NULL, w.pcm, 1, w.count, has_loop ? loop_start : 0, has_loop ? loop_end : 0,
               has_loop, 0, &brr, &brr_len, &brr_loop, &tuning);
    free(w.pcm);
    if (!brr || brr_len == 0) { cli_error(ctx, input, "the encoder produced nothing"); free(brr); return CLI_REFUSED; }

    char brr_path[1024], h_path[1024], ident[256];
    if (cli_output_path(ctx, input, ".brr", brr_path, sizeof brr_path) != CLI_OK ||
        cli_output_path(ctx, input, ".h", h_path, sizeof h_path) != CLI_OK) { free(brr); return CLI_IO; }
    cli_ident(input, ident, sizeof ident);

    char header[1024];
    int hn = snprintf(header, sizeof header,
        "/* %s — generated by opensnes-sample from %s; do not edit */\n"
        "#ifndef OPENSNES_SAMPLE_%s_H\n#define OPENSNES_SAMPLE_%s_H\n\n"
        "#define %s_brr_size %d   /* bytes: %d BRR blocks of 16 samples */\n"
        "#define %s_brr_loop %d   /* byte offset of the loop point; 0 with no loop */\n"
        "#define %s_brr_loops %d   /* 1 = the sample loops */\n"
        "#define %s_rate %d   /* Hz of the source; the DSP plays at 32000 */\n\n"
        "#endif\n",
        h_path + (strrchr(h_path, '/') ? strrchr(h_path, '/') - h_path + 1 : 0),
        input + (strrchr(input, '/') ? strrchr(input, '/') - input + 1 : 0),
        ident, ident, ident, brr_len, brr_len / BRR_BLOCK, ident, brr_loop, ident, has_loop ? 1 : 0,
        ident, w.rate);
    if (hn < 0 || (size_t)hn >= sizeof header) { cli_error(ctx, input, "identifier too long"); free(brr); return CLI_REFUSED; }

    rc = cli_write_file(ctx, brr_path, brr, (size_t)brr_len);
    if (rc == CLI_OK) rc = cli_write_file(ctx, h_path, header, (size_t)hn);
    free(brr);
    if (rc != CLI_OK) return rc;
    if (cli_has(ctx, "save") && (rc = cli_save_settings(ctx, input)) != CLI_OK) return rc;

    if (w.rate > DSP_RATE)
        cli_warn(ctx, input, "%d Hz; the DSP plays it at 32 kHz, so it comes out lower and slower (x%.2f) — resample it to 32000 Hz first",
                 w.rate, (double)DSP_RATE / w.rate);
    if (tuning != 1.0)
        cli_warn(ctx, input, "the loop was resampled to fit 16-sample blocks (tuning x%.4f) — adjust the playback pitch",
                 tuning);

    if (ctx->json) {
        cli_json_object(ctx, NULL);
        cli_json_str(ctx, "input", input);
        cli_json_object(ctx, "source");
        cli_json_int(ctx, "rate", w.rate); cli_json_int(ctx, "bits", w.bits);
        cli_json_int(ctx, "channels", w.channels); cli_json_int(ctx, "samples", w.count);
        cli_json_close(ctx);
        cli_json_array(ctx, "outputs");
        cli_json_object(ctx, NULL); cli_json_str(ctx, "path", brr_path); cli_json_str(ctx, "kind", "brr");
        cli_json_int(ctx, "bytes", brr_len); cli_json_close(ctx);
        cli_json_object(ctx, NULL); cli_json_str(ctx, "path", h_path); cli_json_str(ctx, "kind", "header");
        cli_json_int(ctx, "bytes", hn); cli_json_close(ctx);
        cli_json_close(ctx);
        cli_json_int(ctx, "blocks", brr_len / BRR_BLOCK);
        cli_json_int(ctx, "aram_bytes", brr_len);
        cli_json_bool(ctx, "loops", has_loop);
        cli_json_int(ctx, "loop_offset", brr_loop);
        cli_json_close(ctx);
    } else if (!ctx->quiet) {
        printf("%s: %s -> %s (%d bytes, %d blocks%s)\n", ctx->tool->name, input, brr_path,
               brr_len, brr_len / BRR_BLOCK, has_loop ? ", looping" : "");
    }
    return CLI_OK;
}

static int run_encode(cli_ctx *ctx)
{
    int worst = CLI_OK;
    if (ctx->json) { cli_json_begin(ctx); cli_json_array(ctx, "samples"); }
    for (int i = 0; i < ctx->nargs; i++) {
        int rc = encode_one(ctx, ctx->args[i]);
        if (rc != CLI_OK && ctx->json) {
            cli_json_object(ctx, NULL); cli_json_str(ctx, "input", ctx->args[i]);
            cli_json_int(ctx, "error", rc); cli_json_close(ctx);
        }
        if (rc > worst) worst = rc;
    }
    if (ctx->json) cli_json_end(ctx);
    return worst;
}

/* --------------------------------------------------------------- inspect */

static int has_ext(const char *path, const char *ext)
{
    size_t lp = strlen(path), le = strlen(ext);
    return lp > le && strcmp(path + lp - le, ext) == 0;
}

static int inspect_one(cli_ctx *ctx, const char *input)
{
    if (has_ext(input, ".brr") || has_ext(input, ".BRR")) {
        size_t len = 0;
        unsigned char *b = cli_read_file(ctx, input, &len);
        if (!b) return CLI_IO;
        if (len == 0 || len % BRR_BLOCK) {
            cli_error(ctx, input, "%zu bytes is not a whole number of 9-byte BRR blocks", len);
            free(b);
            return CLI_REFUSED;
        }
        int blocks = (int)(len / BRR_BLOCK);
        int last = b[(size_t)(blocks - 1) * BRR_BLOCK];
        int end_flag = last & 1, loop_flag = (last >> 1) & 1;
        free(b);
        if (ctx->json) {
            cli_json_object(ctx, NULL);
            cli_json_str(ctx, "input", input); cli_json_str(ctx, "kind", "brr");
            cli_json_int(ctx, "bytes", (long)len); cli_json_int(ctx, "blocks", blocks);
            cli_json_int(ctx, "samples", blocks * 16); cli_json_bool(ctx, "loops", loop_flag);
            cli_json_bool(ctx, "end_flag", end_flag); cli_json_int(ctx, "aram_bytes", (long)len);
            cli_json_close(ctx);
        } else {
            printf("%s: BRR, %zu bytes, %d blocks (%d samples, %.3f s at 32 kHz), %s%s\n", input, len,
                   blocks, blocks * 16, blocks * 16 / (double)DSP_RATE, loop_flag ? "looping" : "one-shot",
                   end_flag ? "" : " — the last block lacks the END flag");
        }
        return CLI_OK;
    }
    wav_t w;
    int rc = wav_read(ctx, input, &w);
    if (rc != CLI_OK) return rc;
    free(w.pcm);
    int blocks = (w.count + 15) / 16;
    if (ctx->json) {
        cli_json_object(ctx, NULL);
        cli_json_str(ctx, "input", input); cli_json_str(ctx, "kind", "wav");
        cli_json_int(ctx, "rate", w.rate); cli_json_int(ctx, "bits", w.bits);
        cli_json_int(ctx, "channels", w.channels); cli_json_int(ctx, "samples", w.count);
        cli_json_int(ctx, "brr_blocks", blocks); cli_json_int(ctx, "aram_bytes", (long)blocks * BRR_BLOCK);
        cli_json_bool(ctx, "above_dsp_rate", w.rate > DSP_RATE);
        cli_json_close(ctx);
    } else {
        printf("%s: WAV, %d Hz, %d-bit, %s, %d samples (%.3f s) -> %d BRR blocks, %d bytes of ARAM%s\n",
               input, w.rate, w.bits, w.channels == 1 ? "mono" : "stereo", w.count,
               w.rate ? (double)w.count / w.rate : 0.0, blocks, blocks * BRR_BLOCK,
               w.rate > DSP_RATE ? " (above 32 kHz: plays lower and slower)" : "");
    }
    return CLI_OK;
}

static int run_inspect(cli_ctx *ctx)
{
    int worst = CLI_OK;
    if (ctx->json) { cli_json_begin(ctx); cli_json_array(ctx, "files"); }
    for (int i = 0; i < ctx->nargs; i++) {
        int rc = inspect_one(ctx, ctx->args[i]);
        if (rc != CLI_OK && ctx->json) {
            cli_json_object(ctx, NULL); cli_json_str(ctx, "input", ctx->args[i]);
            cli_json_int(ctx, "error", rc); cli_json_close(ctx);
        }
        if (rc > worst) worst = rc;
    }
    if (ctx->json) cli_json_end(ctx);
    return worst;
}

/* ------------------------------------------------------------------ main */

static const cli_cmd cmds[] = {
    { "encode", "PCM WAV (8/16-bit, mono or stereo) -> .brr + .h beside it", encode_opts, CLI_N(encode_opts),
      "encode res/jump.wav --loop 40 200 --save", 1, run_encode },
    { "inspect", "what a .wav or .brr holds and what it costs in ARAM", NULL, 0,
      "inspect res/*.brr --json", 1, run_inspect },
};

int main(int argc, char **argv)
{
    static const cli_tool tool = {
        "opensnes-sample", TOOL_VERSION,
        "WAV -> BRR samples for the SNES DSP (audioLoadSample)", cmds, CLI_N(cmds),
    };
    return cli_main(&tool, argc, argv);
}
