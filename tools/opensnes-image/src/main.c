#define PI 3.14159265358979323846

static int ends_with(const char *s, const char *suffix)
{
    size_t ls = strlen(s), lx = strlen(suffix);
    return ls > lx && strcmp(s + ls - lx, suffix) == 0;
}

static void upper_of(const char *s, char *out, size_t n)
{
    size_t i;
    for (i = 0; s[i] && i + 1 < n; i++) out[i] = (char)((s[i] >= 'a' && s[i] <= 'z') ? s[i] - 32 : s[i]);
    out[i] = '\0';
}

static FILE *open_glue(cli_ctx *ctx, const char *path, const char *ident, int header)
{
    FILE *f = fopen(path, "w");
    if (!f) { cli_error(ctx, path, "cannot write"); return NULL; }
    if (header)
        fprintf(f, "/* %s.inc — generated by %s %s; do not edit. The data labels live in %s_data.as,\n"
                   " * which the build gathers into assets_gen.asm (docs/tools/CONVENTIONS.md). */\n"
                   "#ifndef ASSET_%s_INC\n#define ASSET_%s_INC\n\n#include <snes.h>\n\n",
                ident, ctx->tool->name, ctx->tool->version, ident, ident, ident);
    else
        fprintf(f, "; %s_data.as — generated by %s %s; one ASSET_SECTION per blob, .include it from assets_gen.asm (the build does)\n\n",
                ident, ctx->tool->name, ctx->tool->version);
    return f;
}

/* =============================================================== hicolor */

#define HC_W 256
#define HC_H 224
#define HC_ROWS (HC_H / 8)
#define HC_SEGS 4
#define HC_SEG_W (HC_W / HC_SEGS)
#define HC_COLORS 15

static unsigned bgr555(const rgb_t c)
{
    return ((c.b & 0xF8) << 7) | ((c.g & 0xF8) << 2) | ((c.r & 0xF8) >> 3);
}

/* Nearest palette entry (squared RGB distance, the first on a tie). */
static int nearest(const rgba_t *p, const rgb_t *pal, int n)
{
    int best = 0;
    long bd = 1L << 30;
    for (int k = 0; k < n; k++) {
        long dr = (long)p->r - pal[k].r, dg = (long)p->g - pal[k].g, db = (long)p->b - pal[k].b;
        long d = dr * dr + dg * dg + db * db;
        if (d < bd) { bd = d; best = k; }
    }
    return best;
}

/* The median cut, then `passes` rounds of k-means: every pixel to its
 * nearest colour, every colour to the mean of its pixels. */
static int quantize_segment(const rgba_t *px, int count, int passes, rgb_t *pal, unsigned char *idx)
{
    int n = quantize_median_cut(px, HC_SEG_W, count / HC_SEG_W, HC_COLORS, pal, idx);
    for (int pass = 0; pass < passes; pass++) {
        long sum[HC_COLORS][3] = { { 0 } };
        long cnt[HC_COLORS] = { 0 };
        for (int i = 0; i < count; i++) {
            int k = nearest(&px[i], pal, n);
            sum[k][0] += px[i].r; sum[k][1] += px[i].g; sum[k][2] += px[i].b; cnt[k]++;
        }
        for (int k = 0; k < n; k++)
            if (cnt[k]) {
                pal[k].r = (unsigned char)((sum[k][0] + cnt[k] / 2) / cnt[k]);
                pal[k].g = (unsigned char)((sum[k][1] + cnt[k] / 2) / cnt[k]);
                pal[k].b = (unsigned char)((sum[k][2] + cnt[k] / 2) / cnt[k]);
            }
    }
    if (passes) for (int i = 0; i < count; i++) idx[i] = (unsigned char)nearest(&px[i], pal, n);
    return n;
}

static const cli_opt hicolor_opts[] = {
    { "passes", 0, CLI_INT, "N", "k-means passes after the median cut, per segment (0 = median cut alone)", "3" },
    CLI_OPT_OUT,
    CLI_OPT_SAVE,
};

static int hicolor_one(cli_ctx *ctx, const char *in)
{
    int rc = cli_load_settings(ctx, in);
    if (rc != CLI_OK) return rc;
    int passes = cli_int(ctx, "passes", 3);
    if (passes < 0 || passes > 64) { cli_error(ctx, in, "--passes %d: 0 to 64", passes); return CLI_REFUSED; }

    unsigned char *raw = NULL;
    unsigned w, h;
    unsigned err = lodepng_decode32_file(&raw, &w, &h, in);
    if (err) { cli_error(ctx, in, "not a PNG this tool reads: %s", lodepng_error_text(err)); return CLI_REFUSED; }
    if (w != HC_W || h != HC_H) {
        cli_error(ctx, in, "%ux%u pixels — HiColor is a full screen of %dx%d (%d tile rows of %d segments of %dx8)", w, h, HC_W, HC_H, HC_ROWS, HC_SEGS, HC_SEG_W);
        free(raw); return CLI_REFUSED;
    }
    const rgba_t *pixels = (const rgba_t *)raw;
    static unsigned char tiles[HC_ROWS * HC_SEGS * 8 * 32], pal[HC_ROWS * HC_SEGS * 16 * 2];
    unsigned char *tp = tiles, *pp = pal;
    unsigned seen[1 << 15 >> 3] = { 0 };
    int on_screen = 0;
    for (int row = 0; row < HC_ROWS; row++)
        for (int seg = 0; seg < HC_SEGS; seg++) {
            rgba_t px[HC_SEG_W * 8];
            unsigned char idx[HC_SEG_W * 8];
            rgb_t spal[HC_COLORS];
            for (int y = 0; y < 8; y++)
                for (int x = 0; x < HC_SEG_W; x++) {
                    px[y * HC_SEG_W + x] = pixels[(row * 8 + y) * HC_W + seg * HC_SEG_W + x];
                    px[y * HC_SEG_W + x].a = 255;   /* the stream reloads whole palettes: nothing is transparent */
                }
            int n = quantize_segment(px, HC_SEG_W * 8, passes, spal, idx);
            /* the segment's palette: black, then its colours (padded with black) */
            *pp++ = 0; *pp++ = 0;
            for (int k = 0; k < HC_COLORS; k++) {
                unsigned c = k < n ? bgr555(spal[k]) : 0;
                *pp++ = (unsigned char)(c & 0xFF); *pp++ = (unsigned char)(c >> 8);
                if (k < n && !(seen[c >> 3] & (1u << (c & 7)))) { seen[c >> 3] |= 1u << (c & 7); on_screen++; }
            }
            for (int t = 0; t < 8; t++) {
                uint8_t cell[64];
                for (int y = 0; y < 8; y++)
                    for (int x = 0; x < 8; x++) cell[y * 8 + x] = (uint8_t)(idx[y * HC_SEG_W + t * 8 + x] + 1);
                convert_tile_4bpp(cell, tp);
                tp += 32;
            }
        }
    free(raw);

    char pic_path[1100], pal_path[1100], inc_path[1100], as_path[1100], ident[256], upper[256];
    if (cli_output_path(ctx, in, ".pic", pic_path, sizeof pic_path) != CLI_OK || cli_output_path(ctx, in, ".pal", pal_path, sizeof pal_path) != CLI_OK ||
        cli_output_path(ctx, in, ".inc", inc_path, sizeof inc_path) != CLI_OK || cli_output_path(ctx, in, "_data.as", as_path, sizeof as_path) != CLI_OK) return CLI_IO;
    cli_ident(in, ident, sizeof ident);
    upper_of(ident, upper, sizeof upper);
    if ((rc = cli_write_file(ctx, pic_path, tiles, sizeof tiles)) != CLI_OK) return rc;
    if ((rc = cli_write_file(ctx, pal_path, pal, sizeof pal)) != CLI_OK) return rc;

    FILE *f = open_glue(ctx, inc_path, ident, 1);
    if (!f) return CLI_IO;
    fprintf(f, "/* HiColor: %d sequential 4 bpp tiles (%d rows x 32), one 16-colour palette per 64x8 segment (%d x %d x 32 bytes).\n"
               " * Load the tiles once; stream the palettes into CGRAM from an H-IRQ, 16 bytes per scanline, as\n"
               " * examples/color/hicolor_1792 does (the tilemap alternates palette banks 0-3 and 4-7 by tile row). */\n",
            HC_ROWS * HC_SEGS * 8, HC_ROWS, HC_ROWS, HC_SEGS);
    fprintf(f, "extern const u8 %s_tiles[], %s_tiles_end[];\nextern const u8 %s_pal[], %s_pal_end[];\n\n", ident, ident, ident, ident);
    fprintf(f, "#define %s_ROWS       %d\n#define %s_SEGMENTS   %d\n#define %s_TILES_SIZE %d\n#define %s_PAL_SIZE   %d\n\n#endif\n",
            upper, HC_ROWS, upper, HC_SEGS, upper, (int)sizeof tiles, upper, (int)sizeof pal);
    fclose(f);
    f = open_glue(ctx, as_path, ident, 0);
    if (!f) return CLI_IO;
    incfile_write_blob(f, ident, "tiles", pic_path);
    incfile_write_blob(f, ident, "pal", pal_path);
    fclose(f);
    if (cli_has(ctx, "save") && (rc = cli_save_settings(ctx, in)) != CLI_OK) return rc;

    if (ctx->json) {
        cli_json_object(ctx, NULL);
        cli_json_str(ctx, "input", in);
        cli_json_int(ctx, "width", w); cli_json_int(ctx, "height", h);
        cli_json_int(ctx, "rows", HC_ROWS); cli_json_int(ctx, "segments", HC_SEGS); cli_json_int(ctx, "colors_per_segment", HC_COLORS);
        cli_json_int(ctx, "palette_entries", HC_ROWS * HC_SEGS * 16); cli_json_int(ctx, "distinct_colors", on_screen);
        cli_json_int(ctx, "passes", passes);
        cli_json_array(ctx, "outputs");
        const char *paths[] = { pic_path, pal_path, inc_path, as_path };
        const char *kinds[] = { "tiles", "palettes", "header", "asm" };
        for (int i = 0; i < 4; i++) { cli_json_object(ctx, NULL); cli_json_str(ctx, "path", paths[i]); cli_json_str(ctx, "kind", kinds[i]); cli_json_close(ctx); }
        cli_json_close(ctx);
        cli_json_int(ctx, "vram_bytes", (long)sizeof tiles);
        cli_json_close(ctx);
    } else if (!ctx->quiet) {
        printf("%s: %s -> %s + .pal (%d tiles, %d palette entries streamed, %d distinct colours on screen)\n", ctx->tool->name, in, pic_path,
               HC_ROWS * HC_SEGS * 8, HC_ROWS * HC_SEGS * 16, on_screen);
    }
    return CLI_OK;
}

static int run_hicolor(cli_ctx *ctx)
{
    int worst = CLI_OK;
    if (ctx->json) { cli_json_begin(ctx); cli_json_array(ctx, "pictures"); }
    for (int i = 0; i < ctx->nargs; i++) {
        int rc = hicolor_one(ctx, ctx->args[i]);
        if (rc != CLI_OK && ctx->json) { cli_json_object(ctx, NULL); cli_json_str(ctx, "input", ctx->args[i]); cli_json_int(ctx, "error", rc); cli_json_close(ctx); }
        if (rc > worst) worst = rc;
    }
    if (ctx->json) cli_json_end(ctx);
    return worst;
}

/* =========================================================== perspective */

static const cli_opt perspective_opts[] = {
    { "angles", 0, CLI_INT, "N", "rotation steps over a full turn, one table set each (2..360)", "48" },
    { "lines", 0, CLI_INT, "N", "scanlines per table (1..224)", "224" },
    { "zoom", 0, CLI_INT, "N", "the scale at the first scanline, in Mode 7 units (1..127; the entry is zoom * 256 / line)", "80" },
    CLI_OPT_OUT,
    CLI_OPT_SAVE,
};

static int run_perspective(cli_ctx *ctx)
{
    if (ctx->nargs != 1 || !ends_with(ctx->args[0], ".toml")) {
        cli_error(ctx, NULL, "perspective takes one settings file, named after the tables: `perspective res/perspective.toml` (with --angles / --zoom and --save to create it)");
        return CLI_USAGE;
    }
    const char *toml = ctx->args[0];
    int rc = cli_load_settings_path(ctx, toml);
    if (rc != CLI_OK) return rc;
    int angles = cli_int(ctx, "angles", 48), lines = cli_int(ctx, "lines", 224), zoom = cli_int(ctx, "zoom", 80);
    if (angles < 2 || angles > 360) { cli_error(ctx, toml, "--angles %d: 2 to 360", angles); return CLI_REFUSED; }
    if (lines < 1 || lines > 224) { cli_error(ctx, toml, "--lines %d: 1 to 224 (the visible scanlines)", lines); return CLI_REFUSED; }
    if (zoom < 1 || zoom > 127) { cli_error(ctx, toml, "--zoom %d: 1 to 127 — the first scanline's entry is zoom * 256, a signed 16-bit Mode 7 term", zoom); return CLI_REFUSED; }

    int stride = lines * 3 + 1;
    size_t size = (size_t)angles * stride;
    unsigned char *tab[3];
    for (int t = 0; t < 3; t++) tab[t] = calloc(size, 1);
    if (!tab[0] || !tab[1] || !tab[2]) { cli_error(ctx, toml, "out of memory"); for (int t = 0; t < 3; t++) free(tab[t]); return CLI_IO; }
    for (int a = 0; a < angles; a++) {
        double th = 2 * PI * a / angles;
        double trig[3] = { cos(th), sin(th), -sin(th) };
        for (int t = 0; t < 3; t++) {
            unsigned char *p = tab[t] + (size_t)a * stride;
            for (int line = 1; line <= lines; line++) {
                long v = lround(trig[t] * zoom * 256.0 / line);
                *p++ = 1;
                *p++ = (unsigned char)(v & 0xFF);
                *p++ = (unsigned char)((v >> 8) & 0xFF);
            }
            *p = 0;   /* the HDMA terminator */
        }
    }

    char stem[256], ident[256], upper[256], path[3][1100], inc_path[1100], as_path[1100];
    static const char *what[3] = { "cos", "sin", "nsin" };
    static const char *ext[3] = { "_cos.hdma", "_sin.hdma", "_nsin.hdma" };
    cli_stem(toml, stem, sizeof stem);
    cli_ident(toml, ident, sizeof ident);
    upper_of(ident, upper, sizeof upper);
    for (int t = 0; t < 3; t++)
        if (cli_output_path(ctx, toml, ext[t], path[t], sizeof path[t]) != CLI_OK) goto io;
    if (cli_output_path(ctx, toml, ".inc", inc_path, sizeof inc_path) != CLI_OK || cli_output_path(ctx, toml, "_data.as", as_path, sizeof as_path) != CLI_OK) goto io;
    for (int t = 0; t < 3; t++)
        if ((rc = cli_write_file(ctx, path[t], tab[t], size)) != CLI_OK) { for (int k = 0; k < 3; k++) free(tab[k]); return rc; }
    for (int t = 0; t < 3; t++) free(tab[t]);

    FILE *f = open_glue(ctx, inc_path, ident, 1);
    if (!f) return CLI_IO;
    fprintf(f, "/* Mode 7 perspective rotation: %d angles (%.4g degrees apart), one HDMA table per matrix term and angle,\n"
               " * entry(line) = trig(angle) * %d * 256 / line in 8.8 fixed point, %d lines of [count 1][word] then a\n"
               " * terminator: %d bytes per angle. Point the four channels at angle a, every frame:\n"
               " *   hdmaSetup(HDMA_CHANNEL_0, HDMA_MODE_1REG_2X, HDMA_DEST_M7A, %s_cos  + a * %s_STRIDE);\n"
               " *   hdmaSetup(HDMA_CHANNEL_1, HDMA_MODE_1REG_2X, HDMA_DEST_M7B, %s_sin  + a * %s_STRIDE);\n"
               " *   hdmaSetup(HDMA_CHANNEL_2, HDMA_MODE_1REG_2X, HDMA_DEST_M7C, %s_nsin + a * %s_STRIDE);\n"
               " *   hdmaSetup(HDMA_CHANNEL_3, HDMA_MODE_1REG_2X, HDMA_DEST_M7D, %s_cos  + a * %s_STRIDE); */\n",
            angles, 360.0 / angles, zoom, lines, stride, ident, upper, ident, upper, ident, upper, ident, upper);
    fprintf(f, "extern const u8 %s_cos[], %s_cos_end[];\nextern const u8 %s_sin[], %s_sin_end[];\nextern const u8 %s_nsin[], %s_nsin_end[];\n\n",
            ident, ident, ident, ident, ident, ident);
    fprintf(f, "#define %s_ANGLES %d\n#define %s_LINES  %d\n#define %s_STRIDE %d\n#define %s_ZOOM   %d\n\n#endif\n",
            upper, angles, upper, lines, upper, stride, upper, zoom);
    fclose(f);
    f = open_glue(ctx, as_path, ident, 0);
    if (!f) return CLI_IO;
    for (int t = 0; t < 3; t++) incfile_write_blob(f, ident, what[t], path[t]);
    fclose(f);
    if (cli_has(ctx, "save") && (rc = cli_save_settings_path(ctx, toml, stem)) != CLI_OK) return rc;

    if (ctx->json) {
        cli_json_begin(ctx);
        cli_json_str(ctx, "input", toml);
        cli_json_int(ctx, "angles", angles); cli_json_int(ctx, "lines", lines); cli_json_int(ctx, "zoom", zoom); cli_json_int(ctx, "stride", stride);
        cli_json_array(ctx, "outputs");
        for (int t = 0; t < 3; t++) { cli_json_object(ctx, NULL); cli_json_str(ctx, "path", path[t]); cli_json_str(ctx, "kind", what[t]); cli_json_int(ctx, "bytes", (long)size); cli_json_close(ctx); }
        cli_json_object(ctx, NULL); cli_json_str(ctx, "path", inc_path); cli_json_str(ctx, "kind", "header"); cli_json_close(ctx);
        cli_json_object(ctx, NULL); cli_json_str(ctx, "path", as_path); cli_json_str(ctx, "kind", "asm"); cli_json_close(ctx);
        cli_json_close(ctx);
        cli_json_int(ctx, "rom_bytes", 3 * (long)size);
        cli_json_end(ctx);
    } else if (!ctx->quiet) {
        printf("%s: %s -> %s_{cos,sin,nsin}.hdma (%d angles x %d lines, %d bytes each, zoom %d)\n", ctx->tool->name, toml,
               stem, angles, lines, (int)size, zoom);
    }
    return CLI_OK;
io:
    for (int t = 0; t < 3; t++) free(tab[t]);
    return CLI_IO;
}

/* =============================================================== inspect */

static int run_inspect(cli_ctx *ctx)
{
    int worst = CLI_OK;
    if (ctx->json) { cli_json_begin(ctx); cli_json_array(ctx, "pictures"); }
    for (int i = 0; i < ctx->nargs; i++) {
        const char *in = ctx->args[i];
        unsigned char *raw = NULL;
        unsigned w, h;
        unsigned err = lodepng_decode32_file(&raw, &w, &h, in);
        if (err) { cli_error(ctx, in, "not a PNG this tool reads: %s", lodepng_error_text(err)); worst = CLI_REFUSED; continue; }
        /* distinct 24-bit colours, and the busiest 64x8 segment in 15-bit colour */
        unsigned char *seen = calloc(1 << 21, 1);
        long distinct = 0;
        if (seen) {
            for (size_t k = 0; k < (size_t)w * h; k++) {
                unsigned c = (raw[k * 4] << 16) | (raw[k * 4 + 1] << 8) | raw[k * 4 + 2];
                if (!(seen[c >> 3] & (1u << (c & 7)))) { seen[c >> 3] |= 1u << (c & 7); distinct++; }
            }
            free(seen);
        }
        int fits = w == HC_W && h == HC_H, worst_seg = 0;
        if (fits)
            for (int row = 0; row < HC_ROWS; row++)
                for (int seg = 0; seg < HC_SEGS; seg++) {
                    unsigned bits[1 << 15 >> 5] = { 0 };
                    int n = 0;
                    for (int y = 0; y < 8; y++)
                        for (int x = 0; x < HC_SEG_W; x++) {
                            const unsigned char *p = raw + (((row * 8 + y) * HC_W) + seg * HC_SEG_W + x) * 4;
                            unsigned c = ((p[2] & 0xF8) << 7) | ((p[1] & 0xF8) << 2) | ((p[0] & 0xF8) >> 3);
                            if (!(bits[c >> 5] & (1u << (c & 31)))) { bits[c >> 5] |= 1u << (c & 31); n++; }
                        }
                    if (n > worst_seg) worst_seg = n;
                }
        free(raw);
        if (ctx->json) {
            cli_json_object(ctx, NULL); cli_json_str(ctx, "input", in);
            cli_json_int(ctx, "width", w); cli_json_int(ctx, "height", h); cli_json_int(ctx, "distinct_colors", distinct);
            cli_json_bool(ctx, "hicolor", fits);
            if (fits) cli_json_int(ctx, "max_colors_in_a_segment", worst_seg);
            cli_json_close(ctx);
        } else if (fits) {
            printf("%s: %ux%u px, %ld distinct colours — a HiColor screen; the busiest 64x8 segment has %d colours in 15-bit (15 kept)\n", in, w, h, distinct, worst_seg);
        } else {
            printf("%s: %ux%u px, %ld distinct colours — not a HiColor screen (%dx%d)\n", in, w, h, distinct, HC_W, HC_H);
        }
    }
    if (ctx->json) cli_json_end(ctx);
    return worst;
}

static const cli_cmd cmds[] = {
    { "hicolor", "a 256x224 picture -> 896 sequential 4 bpp tiles and 112 palettes of 16, one per 64x8 segment, streamed per scanline (1792 colours)",
      hicolor_opts, CLI_N(hicolor_opts), "hicolor res/sunset.png --save", 1, run_hicolor },
    { "perspective", "the Mode 7 perspective-rotation HDMA tables (cos, sin, -sin per angle) for M7A..M7D",
      perspective_opts, CLI_N(perspective_opts), "perspective res/perspective.toml --angles 48 --zoom 80 --save", 1, run_perspective },
    { "inspect", "what a picture holds (size, colours) and whether it is a HiColor screen", NULL, 0, "inspect res/*.png", 1, run_inspect },
};

int main(int argc, char **argv)
{
    static const cli_tool tool = {
        "opensnes-image", TOOL_VERSION, "full-screen pictures (HiColor) and the Mode 7 perspective tables", cmds, CLI_N(cmds),
    };
    return cli_main(&tool, argc, argv);
}
