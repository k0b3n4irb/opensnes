/*
 * opensnes-image — full-screen pictures and the tables that drive them:
 * the HiColor technique and the Mode 7 perspective (the compiled home of
 * two maintainer scripts, hicolor64.py and m7ptables.py).
 *
 *   opensnes-image hicolor     [--passes N] [--out DIR] [--save] [--json] <picture.png>...
 *   opensnes-image perspective [--angles N] [--lines N] [--zoom N] [--out DIR] [--save] [--json] <tables.toml>
 *   opensnes-image inspect     [--json] <picture.png>...
 *
 * `hicolor` cuts a 256x224 picture into 28 tile rows of four 64x8 segments
 * and gives every segment its own 15 colours (index 0 stays black): the
 * tiles (896, sequential, 4 bpp) go to VRAM once, and an H-IRQ streams the
 * segment palettes into CGRAM while the PPU draws, so the screen shows
 * 28 x 64 = 1792 palette entries from a 4 bpp layer (`examples/color/
 * hicolor_1792`, krom's HiColor64PerTileRow).
 *
 * `perspective` writes, for each of --angles rotation steps, one HDMA
 * table per Mode 7 matrix term: entry(line) = trig(angle) * zoom * 256 /
 * line in 8.8 fixed point, the hyperbolic perspective divide, as [count
 * 1][word] per scanline plus a terminator (`examples/mode7/
 * perspective_rotate`, krom's Perspective demo — its tables, byte for byte).
 *
 * Mode 7 pictures themselves are opensnes-tileset --mode 7.
 */
